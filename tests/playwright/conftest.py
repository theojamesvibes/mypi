# ── Helpers ──────────────────────────────────────────────────────────────────


def _free_port() -> int:
    """Reserve a free TCP port by binding ephemerally and releasing it.

    Race-prone in theory, fine in practice for a single-test-process run.
    """
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def _wait_for_health(url: str, timeout: float = 30.0) -> None:
    deadline = time.monotonic() + timeout
    last_err: Exception | None = None
    while time.monotonic() < deadline:
        try:
            r = httpx.get(f"{url}/api/health", timeout=2.0)
            if r.status_code == 200:
                return
        except Exception as exc:
            last_err = exc
        time.sleep(0.3)
    raise RuntimeError(
        f"Live MyPi did not become healthy within {timeout}s "
        f"(last error: {last_err})"
    )


# ── Session: bring up the app ────────────────────────────────────────────────


@pytest.fixture(scope="session")
def live_app() -> Iterator[str]:
    """Start uvicorn in a subprocess and yield its base URL.

    Runs `alembic upgrade head` first so the schema is in place. The DB
    URL must already point at a reachable Postgres — the test driver and
    the app subprocess both connect to the same database.
    """
    if "DATABASE_URL" not in os.environ:
        pytest.skip("DATABASE_URL not set — skipping Playwright suite.")

    env = os.environ.copy()
    # Required app config. Bootstrap password is fixed so logged_in_page
    # can log in without scraping container logs.
    env.setdefault("SECRET_KEY", "ui-test-secret-key-not-for-production")
    env["INITIAL_ADMIN_USER"] = ADMIN_USERNAME
    env["INITIAL_ADMIN_PASSWORD"] = ADMIN_BOOTSTRAP_PASSWORD
    env["PIHOLE_CONFIG_PATH"] = str(TEST_YAML)
    env["ENABLE_API_DOCS"] = "true"  # /docs is exercised by test_navigation
    # Push the polling intervals out so the scheduler never fires during a
    # test run — without real Pi-holes the polls would just log errors.
    env["STATS_POLL_INTERVAL"] = "999999"
    env["QUERIES_POLL_INTERVAL"] = "999999"
    env.setdefault("DATA_RETENTION_DAYS", "999999")
    # Don't ever collide with the parent suite's testcontainer logic.
    env["MYPI_SKIP_TESTCONTAINER"] = "1"

    # Apply migrations against the same DB the subprocess will use.
    # Alembic env.py reads DATABASE_URL out of app.config, which uses
    # asyncpg. For the migration step we swap the driver to psycopg
    # because alembic runs synchronously.
    sync_db_url = env["DATABASE_URL"].replace(
        "postgresql+asyncpg://", "postgresql+psycopg://",
    )
    migrate_env = env.copy()
    migrate_env["DATABASE_URL"] = sync_db_url
    subprocess.run(
        ["alembic", "upgrade", "head"],
        cwd=REPO_ROOT, env=migrate_env, check=True,
    )

    port = _free_port()
    base_url = f"http://127.0.0.1:{port}"

    # Capture stdout/stderr to a log file so failures are diagnosable
    # from CI artifacts without piping through pytest's capture machinery.
    log_path = REPO_ROOT / "playwright-app.log"
    log_fh = open(log_path, "w")
    proc = subprocess.Popen(
        [
            sys.executable, "-m", "uvicorn", "app.main:app",
            "--host", "127.0.0.1", "--port", str(port),
            "--log-level", "info",
        ],
        cwd=REPO_ROOT, env=env, stdout=log_fh, stderr=subprocess.STDOUT,
    )

    try:
        _wait_for_health(base_url)
        yield base_url
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait(timeout=5)
        log_fh.close()


# ── Sync DB session for seeding / cleanup ──────────────────────────────────
#
# Everything below runs synchronously via psycopg. The Playwright sync
# API spins up its own event loop internally (`SyncBase.dispatcher_fiber`)
# and pytest-asyncio spins up another for async fixtures — mixing the two
# from inside one test reliably trips
# "RuntimeError: Cannot run the event loop while another loop is running."
# Sidestepping the conflict by going pure-sync for fixture work is far
# simpler than trying to reconcile the two loops.


@pytest.fixture(scope="session")
def db_engine(live_app):
    """Sync SQLAlchemy engine pointed at the test database.

    Driver swap: app uses asyncpg in prod; tests use psycopg here so the
    engine is plain-sync. Both target the same Postgres.
    """
    from sqlalchemy import create_engine

    sync_url = os.environ["DATABASE_URL"].replace(
        "postgresql+asyncpg://", "postgresql+psycopg://",
    )
    return create_engine(sync_url, future=True)


def _truncate_data(db_engine) -> None:
    """Clear stats/queries/instances/sites — but leave users + app_settings.

    Used as the inner step shared between `db_reset` (which also rewinds
    the admin user) and `db_reset_data` (which leaves users alone so
    a cached session cookie keeps working).
    """
    from sqlalchemy import text

    with db_engine.begin() as conn:
        # Order matters: child rows before parents because of FKs.
        conn.execute(text("TRUNCATE query_logs CASCADE"))
        conn.execute(text("TRUNCATE stats_snapshots CASCADE"))
        conn.execute(text("TRUNCATE pihole_instances CASCADE"))
        conn.execute(text("TRUNCATE site_settings CASCADE"))
        conn.execute(text("TRUNCATE sites CASCADE"))
        # api_keys + revoked_tokens accumulate in tests that exercise
        # the API-key UI / logout flow; clear them so duplicate-name
        # creates don't fail across tests.
        conn.execute(text("TRUNCATE api_keys CASCADE"))
        conn.execute(text("TRUNCATE revoked_tokens CASCADE"))


@pytest.fixture
def db_reset(db_engine):
    """Truncate test data + rewind admin to bootstrap state.

    Used by tests that exercise the login / forced-password-change flow,
    where every test must start from "fresh login required, password
    change forced." `app_settings` is preserved because it stores the
    auto-generated ENCRYPTION_KEY; nuking it would break instance
    encryption mid-run.
    """
    from sqlalchemy import text

    from app.auth import hash_password

    bootstrap_hash = hash_password(ADMIN_BOOTSTRAP_PASSWORD)

    _truncate_data(db_engine)
    with db_engine.begin() as conn:
        conn.execute(
            text(
                "UPDATE users SET hashed_password = :h, "
                "password_change_required = TRUE WHERE username = :u"
            ),
            {"h": bootstrap_hash, "u": ADMIN_USERNAME},
        )


@pytest.fixture
def db_reset_data(db_engine):
    """Truncate test data only — leave users untouched.

    Used by `authed_page` so the session-scoped storage_state cookie
    keeps validating. The fixture also forces the admin into
    "fully-logged-in" state (password rotated, change-required cleared)
    so a previous auth-flow test that left the bootstrap state behind
    doesn't trip the `/change-password` redirect mid-session.
    """
    from sqlalchemy import text

    from app.auth import hash_password

    new_pw_hash = hash_password(ADMIN_NEW_PASSWORD)

    _truncate_data(db_engine)
    with db_engine.begin() as conn:
        conn.execute(
            text(
                "UPDATE users SET hashed_password = :h, "
                "password_change_required = FALSE WHERE username = :u"
            ),
            {"h": new_pw_hash, "u": ADMIN_USERNAME},
        )


@pytest.fixture
def seed_data(db_engine, db_reset_data):
    """Seed a realistic site + instance + 24h of stats + 200 queries.

    Returns a dict with the IDs the test can reference. Depends on
    `db_reset_data` (not `db_reset`) so it composes cleanly with
    `authed_page` — that fixture's session-scoped storage_state cookie
    requires the admin to stay in "fully-logged-in" state.
    """
    from sqlalchemy import text

    site_id = uuid.uuid4()
    instance_id = uuid.uuid4()
    now = datetime.now(timezone.utc)

    with db_engine.begin() as conn:
        conn.execute(
            text(
                "INSERT INTO sites (id, name, slug, is_main, is_active, sort_order) "
                "VALUES (:id, :name, :slug, TRUE, TRUE, 0)"
            ),
            {"id": site_id, "name": "UI Test Site", "slug": "ui-test"},
        )
        conn.execute(
            text(
                "INSERT INTO pihole_instances "
                "(id, site_id, name, url, api_password, color, is_active, "
                " is_master, last_seen_at, version_core, version_ftl, version_web) "
                "VALUES (:id, :site_id, :name, :url, '', :color, TRUE, TRUE, "
                "        :seen, 'v6.0.0', 'v6.0.0', 'v6.0.0')"
            ),
            {
                "id": instance_id, "site_id": site_id,
                "name": "Test-Pihole-1", "url": "http://test-pihole.invalid",
                "color": "#00a65a", "seen": now,
            },
        )

        # 25 hourly stats snapshots — strictly increasing totals so the
        # latest snapshot's `domains_on_blocklist` lands on the dashboard.
        snapshots = []
        for hours_ago in range(24, -1, -1):
            ts = now - timedelta(hours=hours_ago)
            total = 1000 * (24 - hours_ago) + 250
            blocked = total // 4
            snapshots.append({
                "id": uuid.uuid4(), "instance_id": instance_id,
                "collected_at": ts, "status": "online",
                "dns_queries_today": total, "queries_blocked": blocked,
                "percent_blocked": round(blocked / total * 100, 2),
                "domains_on_blocklist": 125000,
                "unique_clients": 12,
                "queries_cached": total // 5,
                "queries_forwarded": total - blocked - (total // 5),
            })
        conn.execute(
            text(
                "INSERT INTO stats_snapshots "
                "(id, instance_id, collected_at, status, dns_queries_today, "
                " queries_blocked, percent_blocked, domains_on_blocklist, "
                " unique_clients, queries_cached, queries_forwarded) VALUES "
                "(:id, :instance_id, :collected_at, :status, :dns_queries_today, "
                " :queries_blocked, :percent_blocked, :domains_on_blocklist, "
                " :unique_clients, :queries_cached, :queries_forwarded)"
            ),
            snapshots,
        )

        # 200 query logs spread across the last hour, mix of allowed/blocked.
        domains = [
            "ads.example.com", "tracker.example.net", "analytics.example.org",
            "cdn.example.com", "api.example.io", "static.example.dev",
        ]
        clients = ["192.168.1.10", "192.168.1.20", "192.168.1.30"]
        rows = []
        for i in range(200):
            ts = now - timedelta(seconds=i * 18)
            blocked = i % 4 == 0
            rows.append({
                "id": uuid.uuid4(), "instance_id": instance_id,
                "pihole_query_id": str(i),
                "timestamp": ts,
                "client_ip": clients[i % len(clients)],
                "client_name": None,
                "query_type": "A",
                "domain": domains[i % len(domains)],
                # GRAVITY is in app.api.stats.BLOCKED_STATUSES; "BLOCKED"
                # is not — using the wrong literal would silently zero
                # the dashboard's blocked-counts assertion.
                "status": "GRAVITY" if blocked else "FORWARDED",
                "reply_type": "NXDOMAIN" if blocked else "IP",
                "reply_time_ms": 1.2 if blocked else 18.7,
            })
        conn.execute(
            text(
                "INSERT INTO query_logs "
                "(id, instance_id, pihole_query_id, timestamp, client_ip, "
                " client_name, query_type, domain, status, reply_type, "
                " reply_time_ms) VALUES "
                "(:id, :instance_id, :pihole_query_id, :timestamp, :client_ip, "
                " :client_name, :query_type, :domain, :status, :reply_type, "
                " :reply_time_ms)"
            ),
            rows,
        )

    return {
        "site_id": str(site_id), "site_slug": "ui-test",
        "instance_id": str(instance_id), "instance_name": "Test-Pihole-1",
    }


