"""Shared fixtures for the Playwright UI test suite.

These tests run against a *live* MyPi process (uvicorn subprocess) and
a real Postgres. They're invoked via `pytest tests/playwright -m playwright`
and excluded from the default `pytest` run by the marker filter in
pytest.ini, so the unit/integration suite stays fast.

Architecture:
  - Session fixture `live_app` runs alembic, spawns uvicorn in a subprocess,
    waits for /api/health to return 200, and tears the process down at exit.
  - Function fixture `db_reset` truncates stats/queries/sites/instances and
    rewinds the admin user back to its bootstrap state between tests.
  - Function fixture `seed_data` inserts a realistic site + instance + 24h
    of stats snapshots + a few hundred query logs so the dashboard renders
    real-looking content.
  - Function fixture `logged_in_page` walks the login + forced-password-
    change flow once and hands the test a Playwright `Page` ready to use.

Required env vars (set by the ui-tests workflow; can be set locally):
  DATABASE_URL              PostgreSQL DSN reachable from the test process
                            *and* from the uvicorn subprocess.
  SECRET_KEY                Any non-empty string; defaulted here if missing.
  ENCRYPTION_KEY            Optional — auto-generated by the app on first run.
  MYPI_SKIP_TESTCONTAINER   Must be "1" so the parent tests/conftest.py
                            doesn't try to spin its own Postgres container.
"""
from __future__ import annotations

import os
import socket
import subprocess
import sys
import time
import uuid
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Iterator

import httpx
import pytest


def pytest_collection_modifyitems(config, items):
    """Auto-tag every test in this directory with the `playwright` marker.

    `pytestmark = pytest.mark.playwright` at module level *does not*
    propagate from a conftest.py to tests in the same directory — only
    the collection hook does. Without this, the default `pytest` run
    (configured with `-m "not playwright"` in pytest.ini) collects the
    UI tests and trips on `alembic upgrade head` because there's no
    Postgres in the fast suite's environment.
    """
    rootpath = Path(__file__).parent.resolve()
    for item in items:
        try:
            item_path = Path(str(item.path)).resolve()
        except Exception:
            continue
        if rootpath in item_path.parents or item_path == rootpath:
            item.add_marker(pytest.mark.playwright)


